"""
dev_run.py — Person B's standalone smoke-test entry point.

Loads the synthetic dummy video and tracks stub, asserts structural
invariants from CONTRACT.md, applies Annotator.draw_annotations, and
saves the annotated output to output_videos/dev_annotated.avi.

This is completely independent of main.py and trackers/ — it uses only
utils/, annotations/, and the stubs generated by generate_dummy_stub.py.

# TODO(A-PUSH): once integration is complete, the stub-loading, invariant
#   checks, and annotation logic from this file should migrate into main.py.
#   dev_run.py can then be removed or repurposed as a CI smoke test.
"""

import argparse
import os
import pickle
import sys

# Allow running from the project root
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from utils import read_video, save_video, get_video_fps
from annotations import Annotator

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

VIDEO_PATH   = "input_videos/dummy_match.avi"
STUB_PATH    = "stubs/dummy_tracks_stub.pkl"
GT_PATH      = "stubs/dummy_ground_truth.pkl"
OUTPUT_PATH  = "output_videos/dev_annotated.avi"

# PLACEHOLDER(PART-3): replace with TeamAssigner
# Placeholder team colours (BGR) derived from ground-truth data
_TEAM_COLORS = {
    1: (40, 40, 220),     # Team 1: Red
    2: (220, 60, 40),     # Team 2: Blue
}
_GK_COLORS = {
    1: (20, 220, 20),     # Team 1 GK: Green
    2: (20, 200, 220),    # Team 2 GK: Yellow/Cyan
}

# PLACEHOLDER(PART-4): Fixed demo possession player ID
DEMO_POSSESSION_PLAYER_ID = 5


# ---------------------------------------------------------------------------
# Invariant & Contract Verification
# ---------------------------------------------------------------------------

def _assert_contract(tracks, num_video_frames):
    """
    Verify CONTRACT.md structural invariants.
    Raises AssertionError with a descriptive message on any violation.
    """
    for key in ("players", "referees", "ball"):
        assert key in tracks, f"tracks missing required key '{key}'"
        assert len(tracks[key]) == num_video_frames, (
            f"tracks['{key}'] has {len(tracks[key])} entries "
            f"but video has {num_video_frames} frames"
        )

    # Spot-check bboxes are plain Python lists of floats/ints
    for frame_num, player_dict in enumerate(tracks["players"]):
        for tid, info in player_dict.items():
            bbox = info.get("bbox")
            assert isinstance(bbox, list), (
                f"frame {frame_num} player {tid}: bbox must be list, got {type(bbox)}"
            )
            assert len(bbox) == 4, (
                f"frame {frame_num} player {tid}: bbox must have 4 elements"
            )
            assert all(isinstance(v, (int, float)) for v in bbox), (
                f"frame {frame_num} player {tid}: bbox values must be numeric"
            )

    # Ball key must be integer 1 (not string "1")
    for frame_num, ball_dict in enumerate(tracks["ball"]):
        for tid in ball_dict:
            assert tid == 1 and isinstance(tid, int), (
                f"frame {frame_num}: ball track_id must be int 1, got {tid!r}"
            )

    print(f"Contract OK — {num_video_frames} frames, all invariants pass.")


def _inject_placeholder_metadata(tracks, gt, demo_possession: bool):
    """
    Inject team colours and demo possession flags for visual testing.
    # PLACEHOLDER(PART-3): replace with TeamAssigner
    # PLACEHOLDER(PART-4): replace with PlayerBallAssigner
    """
    team_per_id = gt.get("team_per_id", {})
    gk_ids = set(gt.get("gk_ids", []))

    for frame_num, player_dict in enumerate(tracks["players"]):
        for pid, p_info in player_dict.items():
            team = team_per_id.get(pid, 1)
            # PLACEHOLDER(PART-3): replace with TeamAssigner
            if pid in gk_ids:
                p_info["team_color"] = _GK_COLORS.get(team, (20, 220, 20))
            else:
                p_info["team_color"] = _TEAM_COLORS.get(team, (40, 40, 220))

            # PLACEHOLDER(PART-4): demo possession flag
            if demo_possession and pid == DEMO_POSSESSION_PLAYER_ID:
                p_info["has_ball"] = True


# ---------------------------------------------------------------------------
# Main Entry Point
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(description="Person B smoke-test & annotation pipeline.")
    parser.add_argument(
        "--demo-possession",
        action="store_true",
        help=f"Set has_ball=True on player #{DEMO_POSSESSION_PLAYER_ID} in every frame (PLACEHOLDER(PART-4))"
    )
    args = parser.parse_args()

    # 1. Load video
    if not os.path.exists(VIDEO_PATH):
        print(f"[dev_run] Video not found: {VIDEO_PATH!r}")
        print("  Run:  python generate_dummy_stub.py  first.")
        sys.exit(1)

    print(f"[dev_run] Loading video: {VIDEO_PATH}")
    frames = read_video(VIDEO_PATH)
    fps = get_video_fps(VIDEO_PATH)
    print(f"  {len(frames)} frames @ {fps:.1f} fps")

    # 2. Load tracks stub
    if not os.path.exists(STUB_PATH):
        print(f"[dev_run] Stub not found: {STUB_PATH!r}")
        print("  Run:  python generate_dummy_stub.py  first.")
        sys.exit(1)

    print(f"[dev_run] Loading tracks stub: {STUB_PATH}")
    with open(STUB_PATH, "rb") as fh:
        tracks = pickle.load(fh)

    # 3. Assert CONTRACT.md invariants
    _assert_contract(tracks, len(frames))

    # 4. Load ground truth for placeholder colours
    if os.path.exists(GT_PATH):
        print(f"[dev_run] Loading ground truth: {GT_PATH}")
        with open(GT_PATH, "rb") as fh:
            gt = pickle.load(fh)
        # PLACEHOLDER(PART-3): replace with TeamAssigner
        # PLACEHOLDER(PART-4): demo-possession
        _inject_placeholder_metadata(tracks, gt, demo_possession=args.demo_possession)
    else:
        print(f"[dev_run] Notice: {GT_PATH} not found; proceeding with neutral default colours.")

    # 5. Render visual annotations with Annotator
    print("[dev_run] Rendering annotations with Annotator.draw_annotations...")
    annotator = Annotator()
    annotated_frames = annotator.draw_annotations(frames, tracks)

    # 6. Save output video
    print(f"[dev_run] Saving annotated video: {OUTPUT_PATH}")
    save_video(annotated_frames, OUTPUT_PATH, fps=fps)
    print(f"[dev_run] Done. Output saved to {OUTPUT_PATH}.")


if __name__ == "__main__":
    main()
